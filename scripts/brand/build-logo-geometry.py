"""Turn the logo's lettering into SVG outlines.

The logo must look the same in every browser, email client and favicon, so
its letters ship as path data instead of live text that depends on a font
being loaded. Run this only when the wordmark or the icon letter changes:

    pip install fonttools uharfbuzz
    python3 scripts/brand/build-logo-geometry.py

It writes src/shared/components/brand/logo-geometry.ts. Both fonts are OFL,
which allows converting them to outlines for a logo.

Wordmark spec (decided 2026-10-22, logo lab option 3 tightened):
  "YardCard"  Fredoka 700, letter-spacing -0.01em
  "ELITE"     Fredoka 300 at 0.72em, letter-spacing 0.035em, 0.22em gap
              after YardCard, raised 0.14em
Icon letter: Lilita One "Y" at 42/64 of the tile, baseline 41, centered.
"""
import os
import urllib.request

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CACHE = os.path.join(ROOT, 'node_modules', '.cache', 'brand-fonts')
OUT = os.path.join(ROOT, 'src', 'shared', 'components', 'brand', 'logo-geometry.ts')

# Google Fonts static files. If a URL stops working, take the new one from
# https://fonts.googleapis.com/css2?family=Fredoka:wght@300;700&family=Lilita+One
FONTS = {
    'fredoka-300': 'https://fonts.gstatic.com/s/fredoka/v17/X7nP4b87HvSqjb_WIi2yDCRwoQ_k7367_B-i2yQag0-mac3OryLMFg.ttf',
    'fredoka-700': 'https://fonts.gstatic.com/s/fredoka/v17/X7nP4b87HvSqjb_WIi2yDCRwoQ_k7367_B-i2yQag0-mac3OFiXMFg.ttf',
    'lilita': 'https://fonts.gstatic.com/s/lilitaone/v17/i7dPIFZ9Zz-WBtRtedDbUEY.ttf',
}


def font_file(key):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, key + '.ttf')
    if not os.path.exists(path):
        urllib.request.urlretrieve(FONTS[key], path)
    return path


def num(v):
    s = f'{v:.2f}'.rstrip('0').rstrip('.')
    return '0' if s == '-0' else s


def set_text(key, text, size, tracking_em, x0, baseline):
    """Shape text with kerning; return (path d, pen x after the run, ink bounds)."""
    path = font_file(key)
    face = hb.Face(hb.Blob.from_file_path(path))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hb.Font(face), buf, {'kern': True})

    tt = TTFont(path)
    glyphs = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    scale = size / tt['head'].unitsPerEm

    x, parts, box = x0, [], None
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        glyph = glyphs[order[info.codepoint]]
        matrix = (scale, 0, 0, -scale, x + pos.x_offset * scale, baseline - pos.y_offset * scale)
        pen = SVGPathPen(glyphs, ntos=num)
        glyph.draw(TransformPen(pen, matrix))
        parts.append(pen.getCommands())
        bounds = BoundsPen(glyphs)
        glyph.draw(TransformPen(bounds, matrix))
        if bounds.bounds:
            b = bounds.bounds
            box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
        x += pos.x_advance * scale + tracking_em * size
    return ''.join(parts), x, box


def advance(key, text, size):
    _, end, _ = set_text(key, text, size, 0, 0, 0)
    return end


# Wordmark in units where the name's font size is 1000 and its baseline is y=0
name_d, name_end, name_box = set_text('fredoka-700', 'YardCard', 1000, -0.01, 0, 0)
elite_size = 720
elite_x = name_end + 0.22 * elite_size
elite_d, _, elite_box = set_text('fredoka-300', 'ELITE', elite_size, 0.035, elite_x, -0.14 * elite_size)

left = min(name_box[0], elite_box[0])
top = min(name_box[1], elite_box[1])
right = max(name_box[2], elite_box[2])
bottom = max(name_box[3], elite_box[3])

# Icon letter, centered on the 64-unit tile like SVG text-anchor="middle"
y_size = 42
y_d, _, _ = set_text('lilita', 'Y', y_size, 0, 32 - advance('lilita', 'Y', y_size) / 2, 41)

with open(OUT, 'w') as f:
    f.write('// Generated by scripts/brand/build-logo-geometry.py. Do not edit by hand.\n')
    f.write('// Outlines of the logo lettering, so the logo never depends on a loaded font.\n\n')
    f.write('/** Wordmark in units where the name is set at 1000 with its baseline at y=0 */\n')
    f.write('export const WORDMARK = {\n')
    f.write(f"  box: {{ x: {num(left)}, y: {num(top)}, width: {num(right - left)}, height: {num(bottom - top)} }},\n")
    f.write('  /** Height of the capitals above the baseline */\n')
    f.write('  capHeight: 700,\n')
    f.write(f"  name: '{name_d}',\n")
    f.write(f"  elite: '{elite_d}',\n")
    f.write('} as const\n\n')
    f.write('/** The icon\'s "Y", in the 64-unit icon tile */\n')
    f.write(f"export const ICON_Y = '{y_d}'\n")

print('wrote', os.path.relpath(OUT, ROOT))
