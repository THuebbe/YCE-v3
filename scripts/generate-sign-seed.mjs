// Generates migrations/20261007_seed_placeholder_sign_library.sql from the
// sign-asset manifest plus the mock keys in catalog-keys.ts.
//   node --experimental-strip-types scripts/generate-sign-seed.mjs
// Re-run after regenerating the manifest; the SQL is idempotent.
import { readFileSync, writeFileSync } from 'node:fs';
import {
  ordinalKey, decorationKey, backdropKey, bookendKey,
  MOCK_ORDINALS, MOCK_DECORATIONS, MOCK_BACKDROPS, MOCK_BOOKENDS,
} from '../src/features/booking/services/catalog-keys.ts';

const QUANTITY = 20;
// The six test agencies (PRODUCT.md "Placeholder data rule": plenty of every sign).
const TEST_AGENCY_SLUGS = [
  'elite-denver', 'lederman-bonds', 'my-business', 'sunny-signs-ca',
  'texas-signs', 'yardcard-elite-west-branch',
];

const manifest = JSON.parse(readFileSync('public/sign-assets/manifest.json', 'utf8'));
const CATEGORY = { letter: 'Letters', number: 'Numbers', punctuation: 'Punctuation', shape: 'Shapes' };

// The manifest is every glyph in every style/colorway at one size per glyph,
// so the SQL stores the glyphs once and cross-joins styles x colorways.
// Asserted below: if that ever stops holding, regenerate differently.
const glyphs = new Map();
for (const a of manifest.assets) {
  const prefix = a.id.slice(0, -`-${a.style}-${a.colorway}`.length);
  const file = a.file.slice(`${a.style}/${a.colorway}/`.length);
  const g = { prefix, type: a.type, character: a.character, width: Math.round(a.widthIn),
              height: Math.round(a.heightIn), file };
  const seen = glyphs.get(prefix);
  if (seen && JSON.stringify(seen) !== JSON.stringify(g)) throw new Error(`glyph ${prefix} differs across colorways`);
  glyphs.set(prefix, g);
}
const expected = new Set(manifest.assets.map(a => a.id));
const crossed = [...glyphs.values()].flatMap(g =>
  manifest.styles.flatMap(st => manifest.colorways.map(c => `${g.prefix}-${st}-${c}`)));
if (crossed.length !== expected.size || !crossed.every(id => expected.has(id))) {
  throw new Error('manifest is not a full glyph x style x colorway grid');
}

const mocks = [];
const mock = (key, name, category, signType, width, height, character = null) =>
  mocks.push({ key, name, category, signType, character, width, height });
for (const o of MOCK_ORDINALS) mock(ordinalKey(o), `Ordinal ${o}`, 'Ordinals', 'ordinal', 18, 18, o);
for (const d of MOCK_DECORATIONS) mock(decorationKey(d), d, 'Decorations', 'decoration', 24, 24);
for (const b of MOCK_BACKDROPS) mock(backdropKey(b), b, 'Backdrops', 'backdrop', 12, 12);
for (const b of MOCK_BOOKENDS) mock(bookendKey(b), b, 'Bookends', 'bookend', 18, 48);

const q = v => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const arr = xs => `ARRAY[${xs.map(q).join(', ')}]`;
const glyphValues = [...glyphs.values()].map(g =>
  `  (${q(g.prefix)}, ${q(g.type)}, ${q(CATEGORY[g.type])}, ${q(g.character)}, ${g.width}, ${g.height}, ${q(g.file)})`
).join(',\n');
const mockValues = mocks.map(m =>
  `  (${q(m.key)}, ${q(m.name)}, ${q(m.category)}, ${q(m.signType)}, ${q(m.character)}, ${m.width}, ${m.height})`
).join(',\n');
const total = expected.size + mocks.length;

const sql = `-- GENERATED by scripts/generate-sign-seed.mjs - do not edit by hand.
-- Placeholder sign library (${total} signs: ${glyphs.size} glyphs x ${manifest.styles.length} style(s)
-- x ${manifest.colorways.length} colorways from the asset manifest, plus ${mocks.length} mock signs with no
-- art yet) and ${QUANTITY} of each for the six test agencies.
-- NOT auto-applied; run after 20261007_booking_inventory_holds.sql. Idempotent.

WITH glyph(prefix, sign_type, category, ch, w, h, file) AS (VALUES
${glyphValues}
),
asset AS (
  SELECT g.prefix || '-' || st || '-' || c AS asset_key,
         COALESCE(g.ch, split_part(g.prefix, '-', 2)) || ' (' || st || '/' || c || ')' AS name,
         g.category, g.sign_type, g.ch, st AS style, c AS colorway, g.w, g.h,
         '/sign-assets/' || st || '/' || c || '/' || g.file AS img
  FROM glyph g
  CROSS JOIN unnest(${arr(manifest.styles)}) AS st
  CROSS JOIN unnest(${arr(manifest.colorways)}) AS c
),
mock(asset_key, name, category, sign_type, ch, w, h) AS (VALUES
${mockValues}
),
all_signs AS (
  SELECT asset_key, name, category, sign_type, ch, style, colorway, w, h, img FROM asset
  UNION ALL
  SELECT asset_key, name, category, sign_type, ch, NULL, NULL, w, h,
         '/placeholder/' || asset_key || '.png' FROM mock
)
INSERT INTO sign_library (id, asset_key, name, category, sign_type, "character",
  style, colorway, size_width, size_height, image_url, is_platform, updated_at)
SELECT 'sign_' || asset_key, asset_key, name, category, sign_type, ch, style,
       colorway, w, h, img, true, now()::timestamp
FROM all_signs
ON CONFLICT (id) DO UPDATE SET
  asset_key = EXCLUDED.asset_key, name = EXCLUDED.name, category = EXCLUDED.category,
  sign_type = EXCLUDED.sign_type, "character" = EXCLUDED."character",
  style = EXCLUDED.style, colorway = EXCLUDED.colorway,
  size_width = EXCLUDED.size_width, size_height = EXCLUDED.size_height,
  image_url = EXCLUDED.image_url, updated_at = now()::timestamp;

INSERT INTO agency_inventory (id, agency_id, sign_id, quantity, available_quantity,
  allocated_quantity, deployed_quantity, updated_at)
SELECT 'inv_' || md5(a.id || ':' || s.id), a.id, s.id, ${QUANTITY}, ${QUANTITY}, 0, 0, now()::timestamp
FROM agencies a
CROSS JOIN sign_library s
WHERE a.slug IN (${TEST_AGENCY_SLUGS.map(q).join(', ')})
  AND s.asset_key IS NOT NULL
ON CONFLICT (agency_id, sign_id) DO NOTHING;
`;

writeFileSync('migrations/20261007_seed_placeholder_sign_library.sql', sql);
console.log(`wrote ${total} signs`);
